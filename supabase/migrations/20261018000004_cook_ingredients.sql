-- CondoCook: 食材マスタ（2026-10-18 追加。RECIPE_SPEC.md D7、docs/CONDOCOOK_1A_DESIGN.md 2.1）
-- - reading: ひらがなの読み（「トリ」→ とり… の前方一致で候補を出す）
-- - aliases: 別名・よくある表記（レシピの材料名の当てはめに使う）
-- - fridge_days / freezer_days: 冷蔵（常温保存の食材は常温）／冷凍での保存の目安日数（フェーズ3で使用。null は目安なし・冷凍に不向き）
-- - is_staple: 「いつもある」の初期候補（調味料など。D9、フェーズ3で使用）
-- - 利用者がレシピ登録中に追加した食材は created_by 付き。管理者が統合（merged_into）・修正する

create table public.ingredients (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 1 and 30),
  reading text not null default '' check (char_length(reading) <= 60),
  aliases text[] not null default '{}',
  category text not null default 'その他'
    check (category in ('肉', '魚介', '野菜', '果物', '卵・乳製品', '豆腐・大豆製品', '米・パン・麺', '調味料', '乾物・粉', 'その他')),
  fridge_days int check (fridge_days between 0 and 3650),
  freezer_days int check (freezer_days between 0 and 3650),
  is_staple boolean not null default false,
  created_by uuid references public.users (id),
  merged_into uuid references public.ingredients (id),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- 統合されていない食材の名前は重複させない
create unique index ingredients_name_key on public.ingredients (lower(name)) where merged_into is null;
create trigger ingredients_updated_at before update on public.ingredients
  for each row execute function public.set_updated_at();

alter table public.ingredients enable row level security;
revoke all on public.ingredients from anon, authenticated;
grant select on public.ingredients to authenticated;
grant insert (name, reading, category, created_by) on public.ingredients to authenticated;
grant update (name, reading, aliases, category, fridge_days, freezer_days, is_staple, merged_into, active) on public.ingredients to authenticated;

create policy ingredients_select on public.ingredients for select to authenticated using (public.is_cook_user());
-- 利用者は名前・読み・分類だけで追加できる（日数・別名などは管理者が整える）
create policy ingredients_insert_own on public.ingredients for insert to authenticated
  with check (public.is_cook_user() and created_by = auth.uid());
create policy ingredients_admin_update on public.ingredients for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

